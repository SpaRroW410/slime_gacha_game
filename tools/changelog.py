#!/usr/bin/env python3
"""Rebuild the commit history section of docs/ROADMAP.md from git, first commit to last.

    python3 tools/changelog.py            # rewrite the section between the changelog markers in docs/ROADMAP.md
    python3 tools/changelog.py --print    # print the section instead

Every commit is listed once, oldest first, grouped by how it reached the project: each merged pull request (its own commits
in order), commits pushed straight to the main line, and - at the end - commits on the current branch that are not merged yet.
Run it after merging (or before opening) a pull request so the history stays complete.
"""
import argparse
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "ROADMAP.md")
START, END = "<!-- changelog:start -->", "<!-- changelog:end -->"
FMT = "%h%x09%ad%x09%s"


def git(*args) -> str:
    return subprocess.run(["git", *args], cwd=ROOT, check=True, capture_output=True, text=True).stdout


def commits(rev_range: str):
    out = git("log", "--reverse", "--no-merges", "--date=short", f"--format={FMT}", rev_range)
    return [line.split("\t", 2) for line in out.splitlines() if line.strip()]


def build() -> str:
    main = [line.split() for line in git("rev-list", "--first-parent", "--reverse", "--parents", "HEAD").splitlines()]
    groups, direct, total = [], [], 0

    def flush():
        nonlocal direct
        if direct:
            groups.append((f"Straight to the main line ({direct[0][1]}{' to ' + direct[-1][1] if direct[-1][1] != direct[0][1] else ''})", direct))
            direct = []

    last_merge = None
    for sha, *parents in main:
        if len(parents) >= 2:                                      # a merged pull request
            flush()
            subject = git("log", "-1", "--format=%s", sha).strip()
            date = git("log", "-1", "--date=short", "--format=%ad", sha).strip()
            m = re.search(r"#(\d+)", subject)
            title = f"Pull request #{m.group(1)}" if m else f"Merge without a pull request number: {subject}"
            groups.append((f"{title} (merged {date})", commits(f"{parents[0]}..{parents[1]}")))
            last_merge = sha
        else:
            info = git("log", "-1", "--date=short", f"--format={FMT}", sha).strip().split("\t", 2)
            direct.append(info)
    # commits after the last merge on the first-parent line belong to the current branch if it is not the main line
    branch = git("rev-parse", "--abbrev-ref", "HEAD").strip()
    if direct and branch not in ("main", "master"):
        groups.append((f"Not merged yet: branch `{branch}`", direct))
        direct = []
    flush()
    lines = [START, "", f"{sum(len(c) for _, c in groups)} commits, oldest first. Generated by `python3 tools/changelog.py` "
             f"at `{git('rev-parse', '--short', 'HEAD').strip()}`.", ""]
    for title, cs in groups:
        if not cs:
            continue
        lines.append(f"### {title}")
        lines.append("")
        for sha, date, subject in cs:
            lines.append(f"- `{sha}` {date} — {subject}")
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description="Rebuild the commit history in docs/ROADMAP.md")
    ap.add_argument("--print", action="store_true", help="print the section instead of writing the file")
    a = ap.parse_args()
    section = build()
    if a.print:
        print(section)
        return 0
    with open(DOC, encoding="utf-8") as f:
        text = f.read()
    if START not in text or END not in text:
        print(f"{DOC} has no changelog markers ({START} ... {END})", file=sys.stderr)
        return 1
    text = text[:text.index(START)] + section + text[text.index(END) + len(END):]
    with open(DOC, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote the history of {section.count(chr(10) + '- `')} commits into docs/ROADMAP.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
